"""The tokens for other tools: Tailwind CSS (version 4 and 3) and Figma variables. tools/build.py calls write(tok, dist).

    dist/tailwind/theme.css          Tailwind 4: @import it after tailwindcss and tokens.css
    dist/tailwind/preset.cjs         Tailwind 3: presets: [require('./tailwind/preset.cjs')]
    dist/figma/colours/<Theme>.tokens.json   one file per theme: drop them all into a new collection, one mode each
    dist/figma/scale/Scale.tokens.json       space, corners, sizes, type, timing and layers, in one mode

Tailwind's utilities read the system's own custom properties (bg-page is var(--page)), so data-theme on any element
re-themes them as it re-themes the components, and tokens.css stays the one place a value is set. Figma takes the
Design Tokens Community Group format (2025.10): a colour is an sRGB object, a size is in px, a duration in seconds. A
fluid size takes its largest value, as on a wide screen.
"""
import json, re

HEAD = '/* Generated by tools/build.py from tokens.json. Do not edit: change tokens.json and build again. */'


def plain(tok):
    """name -> value for every family but colour, shadow and type, which have shapes of their own."""
    out = {}
    for fam, body in tok.items():
        if fam in ('color', 'shadow', 'type') or not isinstance(body, dict) or 'tokens' not in body:
            continue
        out.update({t['name']: t['value'] for t in body['tokens']})
    return out


def styles(tok):
    return [s for g in tok['type']['groups'] for s in g['styles']]


def first_sentence(text):
    text = re.sub(r'`([^`]*)`', r'\1', text or '')
    return text.split('. ')[0].rstrip('.') + '.' if text else ''


# ---------- Tailwind ----------

# The size tokens under names that read well after h-, w-, p- and gap-, and the layout tokens that are a space.
SPACES = {'size-lg': 'control-lg', 'size-md': 'control-md', 'size-sm': 'control-sm', 'size-xs': 'control-xs', 'size-segment': 'segment',
          'size-hit': 'hit', 'size-icon': 'icon', 'card-pad': 'card', 'page-pad': 'gutter', 'section-gap': 'section', 'grid-gap': 'grid'}
WIDTHS = {'container': 'page', 'measure': 'measure'}


def type_rows(tok, fluid):
    """Each type style as a text size with its line height, tracking and weight; the five headings take their fluid size."""
    rows = []
    for s in styles(tok):
        size = f'var(--{s["name"]}-size)' if f'{s["name"]}-size' in fluid else s['fontSize']
        rows.append((s['name'], size, s['lineHeight'], s.get('letterSpacing'), s['fontWeight']))
    return rows


def tailwind4(tok, dark):
    names = plain(tok)
    colours = [t['name'] for t in tok['color']['tokens']]
    fluid = {t['name'] for t in tok.get('fluid', {}).get('tokens', [])}
    out = [HEAD, '''/* Tray UI for Tailwind CSS 4.

     @import "tailwindcss";
     @import "./tokens.css";
     @import "./tailwind/theme.css";

   Then bg-page, text-ink, bg-accent text-on-accent, rounded-card, shadow-float, text-title, h-hit, p-card, max-w-measure.
   Each utility reads the system's own custom property, so a theme (data-theme on <html> or on any element) changes it.
   "reference" keeps Tailwind from declaring these properties again: tokens.css declares them. The spacing scale of
   Tailwind (p-1 is 4px, p-4 is 16px) is the system's own, so it is left as it is. To use only the system's colours,
   put  @theme { --color-*: initial; }  before this file. */''']
    rows = [f'  --color-{n}: var(--{n});' for n in colours]
    rows += [f'  --radius-{t["name"][len("radius-"):]}: var(--{t["name"]});' for t in tok['radius']['tokens']]
    rows += [f'  --shadow-{t["name"][len("shadow-"):]}: var(--{t["name"]});' for t in tok['shadow']['tokens']]
    rows += [f'  --font-{k}: var(--font-{k});' for k in tok['type']['families']]
    for name, size, lh, ls, w in type_rows(tok, fluid):
        rows += [f'  --text-{name}: {size};', f'  --text-{name}--line-height: {lh};', f'  --text-{name}--font-weight: {w};']
        if ls:
            rows.append(f'  --text-{name}--letter-spacing: {ls};')
    rows += [f'  --spacing-{alias}: var(--{name});' for name, alias in SPACES.items() if name in names]
    rows += [f'  --container-{alias}: var(--{name});' for name, alias in WIDTHS.items() if name in names]
    if 'ease' in names:
        rows.append('  --ease-tray: var(--ease);')
    out.append('@theme inline reference {\n' + '\n'.join(rows) + '\n}')
    bps = [t for t in tok.get('breakpoint', {}).get('tokens', [])]
    if bps:  # a media query cannot read a custom property, so the widths are written out
        out.append('/* phone:, tablet:, bento: and header: at the widths where the system\'s own layouts change. */\n@theme {\n'
                   + '\n'.join(f'  --breakpoint-{t["name"][len("bp-"):]}: {t["value"]};' for t in bps) + '\n}')
    sel = ', '.join(f'[data-theme="{d}"], [data-theme="{d}"] *' for d in dark)
    out.append(f'/* dark: for whatever sits in one of the dark themes, not for the visitor\'s system setting. */\n@custom-variant dark (&:where({sel}));')
    return '\n\n'.join(out) + '\n'


def tailwind3(tok, dark):
    names = plain(tok)
    fluid = {t['name'] for t in tok.get('fluid', {}).get('tokens', [])}
    ext = {
        'colors': {t['name']: f'var(--{t["name"]})' for t in tok['color']['tokens']},
        'borderRadius': {t['name'][len('radius-'):]: f'var(--{t["name"]})' for t in tok['radius']['tokens']},
        'boxShadow': {t['name'][len('shadow-'):]: f'var(--{t["name"]})' for t in tok['shadow']['tokens']},
        'fontFamily': {k: f'var(--font-{k})' for k in tok['type']['families']},
        'fontSize': {name: [size, dict({'lineHeight': str(lh), 'fontWeight': str(w)}, **({'letterSpacing': ls} if ls else {}))]
                     for name, size, lh, ls, w in type_rows(tok, fluid)},
        'spacing': {alias: f'var(--{name})' for name, alias in SPACES.items() if name in names},
        'maxWidth': {alias: f'var(--{name})' for name, alias in WIDTHS.items() if name in names},
        'zIndex': {t['name'][len('z-'):]: f'var(--{t["name"]})' for t in tok.get('zIndex', {}).get('tokens', [])},
        'transitionDuration': {t['name'][len('duration-'):]: f'var(--{t["name"]})' for t in tok.get('timing', {}).get('tokens', []) if t['name'].startswith('duration-')},
        'transitionTimingFunction': {'tray': 'var(--ease)'} if 'ease' in names else {},
    }
    sel = ', '.join(f'[data-theme="{d}"], [data-theme="{d}"] *' for d in dark)
    # line comments: a glob such as src/**/*.html would close a block comment
    return (HEAD + '\n// Tray UI for Tailwind CSS 3: a preset.\n//\n'
            "//   // tailwind.config.js\n//   module.exports = { presets: [require('./tailwind/preset.cjs')], content: ['./src/**/*.html'] };\n//\n"
            '// Link tokens.css on the page as well: every value here reads one of its custom properties, so a theme changes them.\n'
            "// The spacing scale of Tailwind (p-1 is 4px) is the system's own. dark: is for whatever sits in a dark theme.\n"
            'module.exports = ' + json.dumps({'darkMode': ['variant', f'&:where({sel})'], 'theme': {'extend': ext}}, indent=2) + ';\n')


# ---------- Figma ----------

def colour(value):
    """A CSS colour, #rrggbb or rgba(r, g, b, a), as a DTCG colour."""
    m = re.fullmatch(r'#([0-9a-fA-F]{6})', value.strip())
    if m:
        rgb, alpha = [int(m.group(1)[i:i + 2], 16) for i in (0, 2, 4)], 1
    else:
        m = re.fullmatch(r'rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)', value.strip())
        if not m:
            raise ValueError(f'a colour Figma cannot take: {value}')
        rgb, alpha = [round(float(m.group(i))) for i in (1, 2, 3)], float(m.group(4) or 1)
    return {'colorSpace': 'srgb', 'components': [round(c / 255, 4) for c in rgb], 'alpha': alpha, 'hex': '#' + ''.join(f'{c:02x}' for c in rgb)}


def px(value):
    """A length in px: rem and em at 16px, and the largest end of a clamp(); None when it is not a length."""
    v = str(value).strip()
    m = re.fullmatch(r'clamp\(.*,\s*([^,]+)\)', v)
    if m:
        v = m.group(1).strip()
    m = re.fullmatch(r'(-?[\d.]+)(px|rem|em)', v)
    if not m:
        return None
    n = float(m.group(1)) * (1 if m.group(2) == 'px' else 16)
    return int(n) if n == int(n) else round(n, 2)


def figma(tok):
    """{path: json} for the colour files, one per theme, and the one scale file."""
    files, first = {}, tok['color']['themes'][0]['id']
    for th in tok['color']['themes']:
        doc = {}
        for t in tok['color']['tokens']:
            v = t['value'] if isinstance(t['value'], str) else t['value'].get(th['id'], t['value'][first])
            doc[t['name']] = {'$type': 'color', '$value': colour(v), '$description': f'--{t["name"]}. ' + first_sentence(t.get('usage', ''))}
        files[f'figma/colours/{th["name"]}.tokens.json'] = doc
    scale = {}
    def put(group, key, entry):
        scale.setdefault(group, {})[key] = entry
    def length(group, key, name, value, usage=''):
        n = px(value)
        if n is not None:
            put(group, key, {'$type': 'dimension', '$value': {'value': n, 'unit': 'px'}, '$description': f'--{name}. ' + first_sentence(usage)})
    for t in tok['spacing']['tokens']:
        length('space', t['name'][len('space-'):], t['name'], t['value'], t.get('usage', ''))
    for t in tok['radius']['tokens']:
        length('radius', t['name'][len('radius-'):], t['name'], t['value'], t.get('usage', ''))
    for t in tok['size']['tokens']:
        length('size', t['name'][len('size-'):], t['name'], t['value'], t.get('usage', ''))
    for t in tok['layout']['tokens'] + tok.get('breakpoint', {}).get('tokens', []):
        length('layout', t['name'], t['name'], t['value'], t.get('usage', ''))
    fluid = {t['name']: t['value'] for t in tok.get('fluid', {}).get('tokens', [])}
    for s in styles(tok):
        size = fluid.get(f'{s["name"]}-size', s['fontSize'])
        put('type', s['name'], {'size': {'$type': 'dimension', '$value': {'value': px(size), 'unit': 'px'}, '$description': f'.{s["name"]}: its size, the largest on a fluid style.'},
                               'weight': {'$type': 'number', '$value': s['fontWeight'], '$description': f'.{s["name"]}: its weight.'}})
    for k, stack in tok['type']['families'].items():
        named = [f.strip().strip('"') for f in stack.split(',') if not f.strip().startswith('ui-') and f.strip() not in ('sans-serif', 'monospace', 'serif')]
        put('font', k, {'$type': 'fontFamily', '$value': named[0], '$description': f'--font-{k}: {stack}'})
    for t in tok.get('timing', {}).get('tokens', []):
        m = re.fullmatch(r'([\d.]+)s', str(t['value']).strip())
        if m:
            put('duration', t['name'][len('duration-'):], {'$type': 'duration', '$value': {'value': float(m.group(1)), 'unit': 's'}, '$description': f'--{t["name"]}. ' + first_sentence(t.get('usage', ''))})
    for t in tok.get('zIndex', {}).get('tokens', []):
        put('layer', t['name'][len('z-'):], {'$type': 'number', '$value': float(t['value']) if '.' in str(t['value']) else int(t['value']), '$description': f'--{t["name"]}.'})
    for t in tok.get('opacity', {}).get('tokens', []):
        put('opacity', t['name'][len('opacity-'):], {'$type': 'number', '$value': float(t['value']), '$description': f'--{t["name"]}.'})
    files['figma/scale/Scale.tokens.json'] = scale
    return files


def write(tok, dist, dark):
    """Write the files under dist/ and return their paths, relative to it."""
    written = []
    (dist / 'tailwind').mkdir(parents=True, exist_ok=True)
    for rel, text in (('tailwind/theme.css', tailwind4(tok, dark)), ('tailwind/preset.cjs', tailwind3(tok, dark))):
        (dist / rel).write_text(text, encoding='utf-8'); written.append(rel)
    for old in (dist / 'figma').rglob('*.json') if (dist / 'figma').exists() else []:
        old.unlink()
    for rel, doc in figma(tok).items():
        (dist / rel).parent.mkdir(parents=True, exist_ok=True)
        (dist / rel).write_text(json.dumps(doc, indent=2, ensure_ascii=False) + '\n', encoding='utf-8'); written.append(rel)
    return written
